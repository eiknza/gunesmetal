create table if not exists public.quote_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 100),
  phone text not null check (char_length(phone) between 7 and 30),
  category text not null check (char_length(category) between 2 and 120),
  product_code text,
  dimensions text not null default '' check (char_length(dimensions) <= 200),
  message text not null check (char_length(message) between 5 and 2000),
  attachment_path text,
  status text not null default 'pending' check (status in ('pending','contacted','quoted','completed','rejected','cancelled')),
  cancelled_at timestamptz,
  cancelled_from_status text,
  created_at timestamptz not null default now()
);
