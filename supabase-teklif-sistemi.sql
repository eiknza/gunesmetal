create or replace function public.submit_quote_request(p_name text,p_phone text,p_category text,p_dimensions text,p_message text,p_attachment_path text default null,p_product_code text default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare new_id bigint; current_user_id uuid := auth.uid();
begin
  if current_user_id is null then raise exception 'LOGIN_REQUIRED'; end if;
  if p_name is null or length(trim(p_name)) < 2 or length(trim(p_name)) > 100 then raise exception 'INVALID_NAME'; end if;
  if p_phone is null or length(regexp_replace(p_phone,'[^0-9+]','','g')) < 10 or length(p_phone) > 30 then raise exception 'INVALID_PHONE'; end if;
  if p_category is null or length(trim(p_category)) < 2 or length(p_category) > 120 then raise exception 'INVALID_CATEGORY'; end if;
  if p_dimensions is not null and length(p_dimensions) > 200 then raise exception 'INVALID_DIMENSIONS'; end if;
  if p_message is null or length(trim(p_message)) < 5 or length(p_message) > 2000 then raise exception 'INVALID_MESSAGE'; end if;
  if p_product_code is not null and length(p_product_code) > 80 then raise exception 'INVALID_PRODUCT_CODE'; end if;
  if p_attachment_path is not null and (length(p_attachment_path)>300 or p_attachment_path !~ ('^'||current_user_id::text||'/[A-Za-z0-9._-]+$')) then raise exception 'INVALID_ATTACHMENT'; end if;
  insert into public.quote_requests(user_id,name,phone,category,product_code,dimensions,message,attachment_path)
  values(current_user_id,trim(p_name),trim(p_phone),trim(p_category),nullif(trim(p_product_code),''),coalesce(trim(p_dimensions),''),trim(p_message),p_attachment_path) returning id into new_id;
  return new_id;
end;
$$;
revoke all on function public.submit_quote_request(text,text,text,text,text,text,text) from public, anon;
grant execute on function public.submit_quote_request(text,text,text,text,text,text,text) to authenticated;
create or replace function public.cancel_my_quote_request(p_quote_id bigint)
returns boolean language plpgsql security definer set search_path = public as $$
declare changed integer;
begin
  if auth.uid() is null then raise exception 'LOGIN_REQUIRED'; end if;
  update public.quote_requests set status='cancelled',cancelled_at=now(),cancelled_from_status=status where id=p_quote_id and user_id=auth.uid() and status in ('pending','contacted','quoted');
  get diagnostics changed = row_count;
  return changed = 1;
end;
$$;
revoke all on function public.cancel_my_quote_request(bigint) from public, anon;
grant execute on function public.cancel_my_quote_request(bigint) to authenticated;
