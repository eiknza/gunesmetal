-- Güneş Metal site istatistikleri
-- Supabase SQL Editor'de bir kez çalıştırın.
create table if not exists public.site_login_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create index if not exists site_login_events_created_at_idx on public.site_login_events(created_at);
create index if not exists site_login_events_user_created_idx on public.site_login_events(user_id, created_at);

create table if not exists public.site_daily_visitors (
  visit_date date not null,
  visitor_id text not null,
  page_views integer not null default 1,
  last_seen timestamptz not null default now(),
  primary key (visit_date, visitor_id)
);
create index if not exists site_daily_visitors_last_seen_idx on public.site_daily_visitors(last_seen);

alter table public.site_login_events enable row level security;
alter table public.site_daily_visitors enable row level security;

create or replace function public.record_member_login()
returns void language plpgsql security definer set search_path = public, auth as $$
begin
  if auth.uid() is null then raise exception 'LOGIN_REQUIRED'; end if;
  insert into public.site_login_events(user_id) values (auth.uid());
end;
$$;
revoke all on function public.record_member_login() from public, anon;
grant execute on function public.record_member_login() to authenticated;

create or replace function public.track_site_visit(p_visitor_id text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if p_visitor_id is null or length(p_visitor_id) < 8 or length(p_visitor_id) > 100 then return; end if;
  insert into public.site_daily_visitors(visit_date, visitor_id, page_views, last_seen)
  values ((now() at time zone 'Europe/Istanbul')::date, p_visitor_id, 1, now())
  on conflict (visit_date, visitor_id) do update set page_views = public.site_daily_visitors.page_views + 1, last_seen = now();
end;
$$;
revoke all on function public.track_site_visit(text) from public;
grant execute on function public.track_site_visit(text) to anon, authenticated;

create or replace function public.get_admin_statistics()
returns jsonb language plpgsql security definer set search_path = public, auth as $$
declare result jsonb; today_tr date := (now() at time zone 'Europe/Istanbul')::date;
begin
  if auth.uid() is null or not public.is_review_admin() then raise exception 'ADMIN_REQUIRED'; end if;
  select jsonb_build_object(
    'total_members', (select count(*) from public.profiles),
    'new_members_today', (select count(*) from public.profiles where (created_at at time zone 'Europe/Istanbul')::date = today_tr),
    'login_events_today', (select count(*) from public.site_login_events where (created_at at time zone 'Europe/Istanbul')::date = today_tr),
    'unique_logged_in_today', (select count(distinct user_id) from public.site_login_events where (created_at at time zone 'Europe/Istanbul')::date = today_tr),
    'unique_visitors_today', (select count(*) from public.site_daily_visitors where visit_date = today_tr),
    'page_views_today', (select coalesce(sum(page_views),0) from public.site_daily_visitors where visit_date = today_tr),
    'active_visitors_now', (select count(*) from public.site_daily_visitors where last_seen > now() - interval '5 minutes'),
    'comments_today', (select count(*) from public.reviews where (created_at at time zone 'Europe/Istanbul')::date = today_tr),
    'last_7_days', coalesce((select jsonb_agg(jsonb_build_object('date', d.day::text, 'date_label', to_char(d.day,'DD.MM'), 'visitors', coalesce(v.visitors,0), 'page_views', coalesce(v.page_views,0), 'logins', coalesce(l.logins,0)) order by d.day) from generate_series(today_tr - 6, today_tr, interval '1 day') as d(day) left join lateral (select count(*) visitors, coalesce(sum(page_views),0) page_views from public.site_daily_visitors where visit_date = d.day::date) v on true left join lateral (select count(*) logins from public.site_login_events where (created_at at time zone 'Europe/Istanbul')::date = d.day::date) l on true), '[]'::jsonb)
  ) into result;
  return result;
end;
$$;
revoke all on function public.get_admin_statistics() from public, anon;
grant execute on function public.get_admin_statistics() to authenticated;
