-- Supabase SQL Editor'de bir kez çalıştırın.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 80),
  email text not null check (char_length(email) between 5 and 254),
  rating integer not null check (rating between 1 and 5),
  message text not null check (char_length(message) between 3 and 1000),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;

-- Ziyaretçiler yalnızca onaylanmış yorumları ve herkese gösterilecek alanları okuyabilir.
drop policy if exists "Anyone can read approved reviews" on public.reviews;
create policy "Anyone can read approved reviews"
on public.reviews for select to anon, authenticated
using (status = 'approved');

-- Ziyaretçiler sadece beklemede olan yorum ekleyebilir.
drop policy if exists "Anyone can submit pending reviews" on public.reviews;
create policy "Anyone can submit pending reviews"
on public.reviews for insert to anon, authenticated
with check (status = 'pending');

-- E-posta adresini API üzerinden de okumayı engelle; yalnızca gerekli sütunları aç.
revoke select on public.reviews from anon, authenticated;
grant select (id, name, rating, message, created_at) on public.reviews to anon, authenticated;
grant insert (name, email, rating, message, status) on public.reviews to anon, authenticated;

